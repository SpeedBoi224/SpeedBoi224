export function findCar(modelId, genId) {
  const car = CARS.find((c) => c.id === modelId);
  if (!car) return null;
  const gen = car.generations.find((g) => g.id === genId);
  if (!gen) return null;
  return { car, gen };
}

export function carLabel(car, gen) {
  return `${gen.years} ${car.make} ${car.model} ${gen.name}`;
}
